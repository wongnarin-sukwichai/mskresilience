<script setup lang="ts">
import AnimatedNumber from '@/components/admin/AnimatedNumber.vue';
import CoverageGauge from '@/components/admin/CoverageGauge.vue';
import ExportButtons from '@/components/admin/ExportButtons.vue';
import LineChart from '@/components/admin/LineChart.vue';
import Reveal from '@/components/admin/Reveal.vue';
import RiskGauge from '@/components/admin/RiskGauge.vue';
import ScatterChart from '@/components/admin/ScatterChart.vue';
import TorRef from '@/components/admin/TorRef.vue';
import { RISK_LEVEL_KEYS, formatThaiDate, hazardLabel, levelOf, riskLevels } from '@/data/riskDisplay';
import AdminLayout from '@/layouts/AdminLayout.vue';
import type { HazardKey, RiskLevelKey, SharedData } from '@/types';
import { Head, Link, router, usePage } from '@inertiajs/vue3';
import { computed, ref } from 'vue';

// แดชบอร์ด (formerly สรุปสำหรับผู้บริหาร; Mayor View, ExecutiveController; TOR 4.1.1(3), 4.3-4). Owner decisions 2026-11-23:
// - Executive Summary: rule-based by default; AI (Claude) mode only reword the same facts, generated by an admin
//   button (never on page view), every number checked; an ⓘ explains the cost and what is sent.
// - Policy Flags use the admin thresholds from ตั้งค่าทั่วไป (relative by default), each with its numbers.
// - Before–after: F4 events and budget rises, compared with the community's HEVC before and after.
interface Flag {
    type: string;
    code: string;
    name: string;
    reason: string;
    label: string;
    icon: string;
    tor: string;
}
interface Investment {
    type: 'f4' | 'budget';
    code: string;
    name: string;
    date: string;
    amount: number;
    label: string;
    before: { year: number; multi: number; level: RiskLevelKey };
    after: { year: number; multi: number; level: RiskLevelKey }[];
    delta: number | null;
    hazard: HazardKey | null;
    parts: { e: number | null; v: number | null; cRaw: number | null } | null;
}
interface Usage {
    at: string;
    status: string;
    error: string | null;
    model: string;
    inputTokens: number | null;
    outputTokens: number | null;
    costUsd: number | null;
    user: string | null;
}

const props = defineProps<{
    empty: boolean;
    year?: number;
    dataDate?: string | null;
    city?: {
        hevc: number | null;
        level: RiskLevelKey | null;
        dominant: HazardKey | null;
        scored: number;
        total: number;
        trend: { year: number; hevc: number | null }[];
    };
    scatter?: { code: string; name: string; hevc: number; level: RiskLevelKey; budgetPerPerson: number }[];
    flags?: {
        thresholds: {
            mode: 'relative' | 'fixed';
            percent: number;
            hevc: number | null;
            budgetPerPerson: number | null;
            recovery: number | null;
            years: number;
            rise: number;
        };
        flags: Flag[];
        counts: Record<string, number>;
    };
    flagTypes?: Record<string, { label: string; icon: string; tor: string }>;
    mcrCoverage?: number | null;
    investments?: Investment[];
    summary?: {
        mode: 'rule' | 'ai';
        rules: string[];
        ai: { text: string; at: string; model: string } | null;
        aiConfigured: boolean;
        facts: Record<string, unknown> | null;
        usage: Usage[] | null;
        pricing: { model: string; inputPerMTok: number; outputPerMTok: number; usdToThb: number };
    };
}>();

const isAdmin = computed(() => usePage<SharedData>().props.auth.user?.role === 'admin');

// ── Executive summary ──
const showRules = ref(false);
const usingAi = computed(() => props.summary?.mode === 'ai' && !!props.summary.ai && !showRules.value);
const generating = ref(false);
function generate() {
    router.post(
        route('executive.ai-summary'),
        {},
        { preserveScroll: true, onStart: () => (generating.value = true), onFinish: () => (generating.value = false) },
    );
}
const costOpen = ref(false);
// A typical call: the facts (~2,500 tokens with the instructions) in, a paragraph plus the model's thinking (~2,000) out.
const estimate = computed(() => {
    const p = props.summary?.pricing;
    if (!p) return null;
    const usd = (2500 * p.inputPerMTok + 2000 * p.outputPerMTok) / 1_000_000;
    return { usd, thb: usd * p.usdToThb };
});
const totalSpent = computed(() => (props.summary?.usage ?? []).reduce((s, u) => s + (u.costUsd ?? 0), 0));

// ── Scatter HEVC × budget per person (TOR 4.1.1(3)-1) ──
const scatterPoints = computed(() =>
    (props.scatter ?? []).map((c) => ({
        id: c.code,
        label: `${c.code} ${c.name}`,
        x: c.hevc,
        y: c.budgetPerPerson,
        color: riskLevels[levelOf(c.hevc)].color,
        emphasis: (props.flags?.flags ?? []).some((f) => f.code === c.code && f.type === 'high_risk_low_budget'),
    })),
);
const baht = (v: number) => Math.round(v).toLocaleString('th-TH');
// The 4 quadrants of the scatter, cut by the same Policy Flag thresholds as its dashed lines (owner 2026-11-23: the
// card is split in half, chart left + this summary right, and the chart opens large in a modal).
const scatterOpen = ref(false);
const QUADRANTS = [
    { key: 'hl', label: 'เสี่ยงสูง งบต่ำ', hint: 'ควรพิจารณาก่อน', high: true, lowBudget: true, tone: 'border-red-200 bg-red-50 text-red-700' },
    {
        key: 'hh',
        label: 'เสี่ยงสูง งบสูง',
        hint: 'มีงบแล้ว ติดตามผล',
        high: true,
        lowBudget: false,
        tone: 'border-amber-200 bg-amber-50 text-amber-700',
    },
    { key: 'll', label: 'เสี่ยงต่ำ งบต่ำ', hint: '', high: false, lowBudget: true, tone: 'border-slate-200 bg-slate-50 text-slate-600' },
    { key: 'lh', label: 'เสี่ยงต่ำ งบสูง', hint: '', high: false, lowBudget: false, tone: 'border-emerald-200 bg-emerald-50 text-emerald-700' },
] as const;
const quadrants = computed(() => {
    const t = props.flags?.thresholds;
    return QUADRANTS.map((q) => ({
        ...q,
        items: (props.scatter ?? [])
            .filter(
                (c) =>
                    t?.hevc != null &&
                    t?.budgetPerPerson != null &&
                    c.hevc >= t.hevc === q.high &&
                    c.budgetPerPerson <= t.budgetPerPerson === q.lowBudget,
            )
            .sort((a, b) => b.hevc - a.hevc),
    }));
});

// ── Flags grouped by type ──
const flagGroups = computed(() =>
    Object.entries(props.flagTypes ?? {}).map(([type, meta]) => ({
        type,
        ...meta,
        items: (props.flags?.flags ?? []).filter((f) => f.type === type),
    })),
);
const totalFlagged = computed(() => new Set((props.flags?.flags ?? []).map((f) => f.code)).size);
const thresholdText = computed(() => {
    const t = props.flags?.thresholds;
    if (!t) return '';
    const cut = (v: number | null, d = 1) => (v === null ? '–' : v.toLocaleString('th-TH', { maximumFractionDigits: d }));
    return t.mode === 'relative'
        ? `เทียบกันเองในเมือง: เสี่ยงสูง = ${t.percent}% บนสุด (HEVC ≥ ${cut(t.hevc)}), งบต่ำ = ${t.percent}% ล่างสุด (≤ ${cut(t.budgetPerPerson, 0)} บาท/คน), ฟื้นฟูต่ำ = ${t.percent}% ล่างสุด (≤ ${cut(t.recovery)}) · ต่อเนื่อง ${t.years} ปี · เพิ่มขึ้น ≥ ${t.rise} คะแนน`
        : `เกณฑ์ตายตัว: HEVC ≥ ${cut(t.hevc)}, งบ ≤ ${cut(t.budgetPerPerson, 0)} บาท/คน, ฟื้นฟู ≤ ${cut(t.recovery)} · ต่อเนื่อง ${t.years} ปี · เพิ่มขึ้น ≥ ${t.rise} คะแนน`;
});

const trendBands = RISK_LEVEL_KEYS.map((k, i) => ({ from: [0, 25, 50, 75][i], to: [25, 50, 75, 100][i], color: riskLevels[k].color }));
const signed = (v: number | null, d = 1) => (v === null ? '–' : `${v > 0 ? '+' : ''}${v.toFixed(d)}`);
const card = 'rounded-2xl border border-slate-100 bg-white p-5 shadow-sm';
</script>

<template>
    <Head title="แดชบอร์ด" />

    <AdminLayout title="แดชบอร์ด">
        <div class="mb-6 flex flex-wrap items-start justify-between gap-3">
            <div class="border-l-4 border-blue-600 pl-4">
                <h1 class="text-2xl font-bold text-slate-800">แดชบอร์ด<TorRef :refs="['4.1.1(3)', '4.3-4']" /></h1>
                <p v-if="!empty" class="mt-1 text-sm text-slate-500">
                    ข้อมูลล่าสุด ปีงบประมาณ {{ year }} · ณ {{ dataDate ? formatThaiDate(dataDate) : '–' }} · คำนวณจาก {{ city?.scored }} จาก
                    {{ city?.total }} ชุมชน
                </p>
            </div>
            <ExportButtons v-if="!empty" :excel-href="route('export.flags')" />
        </div>

        <div v-if="empty" class="rounded-2xl border border-slate-100 bg-white p-10 text-center text-sm text-slate-500 shadow-sm">
            ยังไม่มีข้อมูลสำหรับสรุป
        </div>

        <template v-else-if="city && summary && flags">
            <!-- Executive Summary (4.1.1(3)-4) -->
            <Reveal>
                <div :class="[card, 'mb-5 border-blue-100 bg-gradient-to-br from-blue-50 to-white']">
                    <div class="flex flex-wrap items-center justify-between gap-3">
                        <h2 class="font-semibold text-slate-800">
                            <i class="fa-solid fa-file-lines mr-1.5 text-blue-600"></i>สรุปภาพรวม (Executive Summary)<TorRef
                                :refs="['4.1.1(3)-4', 'คุณลักษณะ 2.4-4']"
                            />
                        </h2>
                        <div class="flex flex-wrap items-center gap-2 text-xs">
                            <span v-if="usingAi" class="rounded-full bg-violet-100 px-2.5 py-1 font-medium text-violet-700">
                                <i class="fa-solid fa-wand-magic-sparkles mr-1"></i>สรุปโดย AI · {{ formatThaiDate(summary.ai!.at.slice(0, 10)) }}
                            </span>
                            <span v-else class="rounded-full bg-slate-100 px-2.5 py-1 font-medium text-slate-600">
                                <i class="fa-solid fa-gears mr-1"></i>สรุปอัตโนมัติ (แบบกฎ)
                            </span>
                            <button
                                v-if="summary.ai && summary.mode === 'ai'"
                                type="button"
                                class="text-blue-600 hover:underline"
                                @click="showRules = !showRules"
                            >
                                {{ showRules ? 'ดูสรุปโดย AI' : 'ดูแบบกฎ' }}
                            </button>
                            <template v-if="isAdmin && summary.mode === 'ai'">
                                <button
                                    type="button"
                                    :disabled="!summary.aiConfigured || generating"
                                    :title="
                                        summary.aiConfigured
                                            ? 'เรียก AI หนึ่งครั้งจากข้อมูลชุดปัจจุบัน'
                                            : 'ยังไม่ได้ตั้งค่า ANTHROPIC_API_KEY บนเซิร์ฟเวอร์'
                                    "
                                    class="rounded-lg bg-violet-600 px-3 py-1.5 font-medium text-white hover:bg-violet-700 disabled:cursor-not-allowed disabled:opacity-50"
                                    @click="generate"
                                >
                                    <i class="fa-solid mr-1" :class="generating ? 'fa-spinner fa-spin' : 'fa-wand-magic-sparkles'"></i>
                                    {{ summary.ai ? 'สร้างใหม่ด้วย AI' : 'สร้างสรุปด้วย AI' }}
                                </button>
                            </template>
                            <button
                                v-if="isAdmin"
                                type="button"
                                class="flex h-7 w-7 items-center justify-center rounded-full border border-slate-200 text-slate-500 hover:bg-slate-50"
                                title="ข้อมูลค่าใช้จ่ายและข้อมูลที่ส่งให้ AI"
                                @click="costOpen = true"
                            >
                                <i class="fa-solid fa-circle-info"></i>
                            </button>
                        </div>
                    </div>
                    <p v-if="usingAi" class="mt-3 leading-relaxed text-slate-700">{{ summary.ai!.text }}</p>
                    <ul v-else class="mt-3 space-y-1.5 text-slate-700">
                        <li v-for="(s, i) in summary.rules" :key="i" class="flex gap-2 leading-relaxed">
                            <i class="fa-solid fa-circle mt-2 text-[6px] text-blue-400"></i><span>{{ s }}</span>
                        </li>
                    </ul>
                    <p v-if="summary.mode === 'ai' && !summary.ai" class="mt-2 text-xs text-slate-400">
                        ยังไม่มีสรุปโดย AI สำหรับข้อมูลชุดนี้ จึงแสดงแบบกฎ{{ isAdmin ? ' (กดปุ่มสร้างสรุปด้วย AI)' : '' }}
                    </p>
                </div>
            </Reveal>

            <!-- City / MCR / flag counts -->
            <div class="mb-5 grid grid-cols-1 gap-5 lg:grid-cols-3">
                <div :class="card">
                    <h2 class="font-semibold text-slate-800">ความเสี่ยงรวมของเมือง</h2>
                    <div class="mt-2 flex items-center gap-3">
                        <div class="w-40 shrink-0"><RiskGauge :value="city.hevc" /></div>
                        <div>
                            <p class="text-3xl font-bold text-slate-800">
                                <AnimatedNumber :value="city.hevc" :format="(v: number) => v.toFixed(1)" />
                            </p>
                            <span v-if="city.level" class="rounded-full px-2 py-0.5 text-xs font-medium" :class="riskLevels[city.level].badge">{{
                                riskLevels[city.level].label
                            }}</span>
                            <p v-if="city.dominant" class="mt-1 text-xs text-slate-500">ภัยเด่น {{ hazardLabel[city.dominant] }}</p>
                        </div>
                    </div>
                    <LineChart
                        v-if="city.trend.length > 1"
                        :categories="city.trend.map((p) => `ปีงบ ${p.year}`)"
                        :series="[{ label: 'HEVC เมือง', color: '#2563eb', values: city.trend.map((p) => p.hevc) }]"
                        :max="50"
                        :bands="trendBands"
                        :height="150"
                        :width="360"
                    />
                </div>
                <div :class="[card, 'flex flex-col items-center text-center']">
                    <h2 class="self-start font-semibold text-slate-800">หลักฐาน MCR2030<TorRef :refs="['4.1.1(3)-2']" /></h2>
                    <CoverageGauge class="mt-2" :value="mcrCoverage ?? null" />
                    <p class="text-xs text-slate-500">ความครอบคลุมของหลักฐานเฉลี่ยทั้งเมือง (ไม่ใช่คะแนนความยืดหยุ่น)</p>
                    <Link :href="route('mcr2030-kpi.index', { tab: 'mcr' })" class="mt-2 text-xs text-blue-600 hover:underline"
                        >ดูรายละเอียด 10 หลักสำคัญ →</Link
                    >
                </div>
                <div :class="card">
                    <h2 class="font-semibold text-slate-800">สัญญาณที่ควรติดตาม<TorRef :refs="['4.1.1(3)-3']" /></h2>
                    <p class="mt-1 text-xs text-slate-500">{{ totalFlagged }} ชุมชนเข้าเงื่อนไขอย่างน้อยหนึ่งข้อ</p>
                    <ul class="mt-3 space-y-2">
                        <li v-for="g in flagGroups" :key="g.type" class="flex items-center gap-3 rounded-xl bg-slate-50 px-3 py-2">
                            <span
                                class="flex h-8 w-8 items-center justify-center rounded-full"
                                :class="g.items.length ? 'bg-red-100 text-red-600' : 'bg-slate-100 text-slate-400'"
                                ><i :class="g.icon"></i
                            ></span>
                            <span class="flex-1 text-sm text-slate-700">{{ g.label }}</span>
                            <span class="text-lg font-bold" :class="g.items.length ? 'text-red-600' : 'text-slate-400'"
                                ><AnimatedNumber :value="g.items.length"
                            /></span>
                        </li>
                    </ul>
                </div>
            </div>

            <!-- Scatter HEVC × budget (4.1.1(3)-1) -->
            <Reveal>
                <div :class="[card, 'mb-5']">
                    <div class="flex items-start justify-between gap-3">
                        <h2 class="font-semibold text-slate-800">
                            ความเสี่ยง (HEVC) เทียบกับงบประมาณด้านภัย<TorRef :refs="['4.1.1(3)-1', 'คุณลักษณะ 2.4-1']" />
                        </h2>
                        <button
                            type="button"
                            class="flex shrink-0 items-center gap-1.5 rounded-xl border border-slate-200 px-3 py-1.5 text-xs font-medium text-slate-600 hover:bg-slate-50 print:hidden"
                            @click="scatterOpen = true"
                        >
                            <i class="fa-solid fa-expand"></i>ขยายกราฟ
                        </button>
                    </div>
                    <p class="text-xs text-slate-500">
                        แต่ละจุดคือหนึ่งชุมชน · แกนนอน = HEVC ความเสี่ยงรวม · แกนตั้ง = งบด้านภัยเฉลี่ยย้อนหลัง 3 ปี ต่อประชากร · เส้นประ = เกณฑ์
                        Policy Flag · จุดมีวง = เสี่ยงสูงแต่งบต่ำ · คลิกจุดเพื่อเปิดแผนที่ชุมชน
                    </p>
                    <div class="mt-3 grid items-start gap-5 lg:grid-cols-2">
                        <ScatterChart
                            :points="scatterPoints"
                            x-label="HEVC ความเสี่ยงรวม (0–100)"
                            y-label="งบด้านภัย (บาท/คน)"
                            :x-max="100"
                            :split-x="flags.thresholds.hevc"
                            :split-y="flags.thresholds.budgetPerPerson"
                            :quadrant-labels="{
                                bottomRight: 'เสี่ยงสูง งบต่ำ',
                                topRight: 'เสี่ยงสูง งบสูง',
                                bottomLeft: 'เสี่ยงต่ำ งบต่ำ',
                                topLeft: 'เสี่ยงต่ำ งบสูง',
                            }"
                            :format-y="baht"
                            @select="(code: string) => router.visit(route('community-map.index', { community: code }))"
                        />
                        <div>
                            <p class="mb-2 text-xs text-slate-500">
                                แบ่งตามเส้นประ: เสี่ยงสูง = HEVC ≥ {{ flags.thresholds.hevc?.toFixed(1) ?? '–' }} · งบต่ำ = ≤
                                {{ flags.thresholds.budgetPerPerson === null ? '–' : baht(flags.thresholds.budgetPerPerson) }} บาท/คน
                            </p>
                            <div class="grid grid-cols-2 gap-3">
                                <div v-for="q in quadrants" :key="q.key" class="rounded-xl border p-3" :class="q.tone">
                                    <div class="flex items-baseline justify-between gap-2">
                                        <p class="text-sm font-semibold">{{ q.label }}</p>
                                        <p class="text-2xl font-bold"><AnimatedNumber :value="q.items.length" /></p>
                                    </div>
                                    <p class="text-[11px] opacity-80">{{ q.hint || 'ชุมชน' }}</p>
                                    <ul v-if="q.high && q.items.length" class="mt-2 space-y-0.5 text-xs">
                                        <li v-for="c in q.items.slice(0, 5)" :key="c.code">
                                            <Link
                                                :href="route('community-map.index', { community: c.code })"
                                                class="flex justify-between gap-2 hover:underline"
                                            >
                                                <span class="truncate">{{ c.name }}</span>
                                                <span class="shrink-0 tabular-nums">{{ c.hevc.toFixed(1) }} · {{ baht(c.budgetPerPerson) }} ฿</span>
                                            </Link>
                                        </li>
                                        <li v-if="q.items.length > 5" class="opacity-70">และอีก {{ q.items.length - 5 }} ชุมชน</li>
                                    </ul>
                                </div>
                            </div>
                        </div>
                    </div>
                </div>
            </Reveal>

            <!-- Policy Flags (4.1.1(3)-3, 4.1.2) -->
            <Reveal>
                <div :class="[card, 'mb-5']">
                    <div class="flex flex-wrap items-start justify-between gap-2">
                        <h2 class="font-semibold text-slate-800">
                            ระบบแจ้งเตือนอัตโนมัติ (Policy Flag)<TorRef :refs="['4.1.1(3)-3', '4.1.2', 'คุณลักษณะ 2.4-3', 'คุณลักษณะ 2.6-2']" />
                        </h2>
                        <Link v-if="isAdmin" :href="route('system-settings.index')" class="text-xs text-blue-600 hover:underline">
                            <i class="fa-solid fa-sliders mr-1"></i>ตั้งเกณฑ์
                        </Link>
                    </div>
                    <p class="mt-1 text-xs text-slate-500">{{ thresholdText }}</p>
                    <div class="mt-4 grid grid-cols-1 gap-4 md:grid-cols-2">
                        <div v-for="g in flagGroups" :key="g.type" class="rounded-xl border border-slate-100 p-4">
                            <h3 class="flex items-center gap-2 text-sm font-semibold text-slate-700">
                                <i :class="[g.icon, g.items.length ? 'text-red-500' : 'text-slate-300']"></i>{{ g.label }}
                                <span class="ml-auto rounded-full bg-slate-100 px-2 text-xs text-slate-600">{{ g.items.length }}</span>
                            </h3>
                            <ul v-if="g.items.length" class="mt-2 divide-y divide-slate-50">
                                <li v-for="f in g.items" :key="f.code" class="flex items-start gap-1">
                                    <Link
                                        :href="route('community-map.index', { community: f.code })"
                                        class="block min-w-0 flex-1 rounded-lg px-2 py-2 hover:bg-slate-50"
                                    >
                                        <p class="text-sm font-medium text-slate-800">{{ f.code }} {{ f.name }}</p>
                                        <p class="text-xs text-slate-500">{{ f.reason }}</p>
                                    </Link>
                                    <Link
                                        :href="route('reports.funding', f.code)"
                                        class="mt-2 shrink-0 rounded-lg px-2 py-1 text-xs text-blue-600 hover:bg-blue-50 print:hidden"
                                        title="รายงานหลักฐานประกอบการเสนอของบประมาณ"
                                    >
                                        <i class="fa-solid fa-file-invoice-dollar"></i>
                                    </Link>
